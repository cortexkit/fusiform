/// A store whose contents are fixed, so the payload is reproducible.
///
/// Every instant IN THE STORE is a literal, so nothing about the data moves
/// between runs. One field in one payload still does: a read with no `at_ms`
/// resolves to now by definition, and its `resolved_at_ms` is a wall clock
/// reading. That case substitutes a placeholder — and the point-in-time case
/// below pins the same field exactly, so the field's spelling and type are
/// covered while its unpinnable value is not pretended to be fixed.
///
/// This is narrower than it first looked. The initial version of this file
/// claimed every instant was a literal, which was false for exactly that one
/// read, and the test failed on its second run.
fn store() -> (CatalogStore, tempfile::TempDir) {
    let dir = tempfile::tempdir().unwrap();
    let store = CatalogStore::open(&StorageDescriptor {
        module_id: "fusiform".to_string(),
        storage_namespace: "default".to_string(),
        isolation: Isolation::Module,
        backend: StorageBackend::Sqlite {
            path: dir.path().join("store.db").to_string_lossy().to_string(),
        },
    })
    .unwrap();

    // A seed, so the catalog exists.
    store
        .record_observation(&NewObservation {
            source: SourceId::ModelsDev,
            observed_at: Timestamp(1_000),
            outcome: ObservationOutcome::Seeded,
            normalized_hash: Some("seed-hash".into()),
            raw_hash: Some("seed-raw".into()),
            etag: None,
            duration_ms: Some(12),
            detail: None,
        })
        .unwrap();
    // ONE document, not two.
    //
    // A second `plan_ingest` at the same instant would diff the synthetic
    // document against the store and tombstone every model from the first --
    // ingest treats "absent from this document" as a withdrawal, which is
    // correct and is exactly why a fixture must present one document rather
    // than two. Caught by the schema's uniqueness constraint on first run.
    let catalog = normalize_models_dev(merged_upstream().as_bytes())
        .unwrap()
        .catalog;
    let plan = plan_ingest(&store, &catalog, Timestamp(1_000), BoundaryKind::Seed, None).unwrap();
    store.append_eras(&plan.eras).unwrap();

    // A model whose reasoning capability is UNKNOWN, from a document that is
    // deliberately synthetic and labelled as such.
    //
    // Every other row in this fixture comes from a real upstream cut, which is
    // this repository's rule: a hand-written fixture encodes its author's
    // understanding of the format. This one cannot, and the reason is worth
    // stating rather than hiding. Measured on the live document today: all
    // 6,291 models publish the `reasoning` key, so ABSENT does not occur
    // upstream and cannot be cut from it.
    //
    // It is pinned anyway because the null is the whole point of BROCA's
    // parser fix — `as_bool()` returns None on a JSON null, so absent, false
    // and null all collapse to false, and a capable model silently stops
    // reasoning. Their deny-drift test vendors THIS fixture, so without a null
    // row their check cannot cover the case it exists for.
    //
    // The alternative was to leave the wire shape unpinned until the upstream
    // produces one, which means the first real occurrence is also the first
    // test of the path.

    // A SECOND INGEST WITH ONE RATE WITHDRAWN, so the fixture carries an
    // `unpriced` rate produced by the ingest path rather than written by hand.
    //
    // `unpriced/missing_rate` is a TOMBSTONE: the upstream described the model
    // and stopped publishing a rate it used to publish. 153 eras in the live
    // catalog carry it today, so it is an ordinary served state rather than an
    // edge case — and the one a consumer most needs to get right, because a
    // withdrawn rate is emphatically NOT zero. A decoder that defaults it
    // charges nothing for a model that bills.
    //
    // Generated by `plan_ingest` rather than appended as a literal, for the
    // reason the inheritance case exists: a hand-written value pins what I
    // BELIEVE the producer emits, and the fixture's whole job is to pin what it
    // ACTUALLY emits. If `withdrawal_value` changes, this reddens; a literal
    // would not.
    let withdrawn = {
        let mut doc: serde_json::Value =
            serde_json::from_str(&merged_upstream()).expect("the merged upstream parses");
        let cost = doc["zhipuai"]["models"]["glm-4.5-flash"]["cost"]
            .as_object_mut()
            .expect("glm-4.5-flash has a cost object");
        assert!(
            cost.remove("cache_write").is_some(),
            "the key being withdrawn must exist first, or this ingest is a no-op \
             and the fixture silently loses the tombstone"
        );

        // A WHOLE MODEL withdrawn as well, so the fixture carries a RETIRED
        // row. The `retired` array was added for a consumer whose roster went
        // stale on an upstream rename, and it appeared nowhere in these bytes
        // — the field exists precisely so a named read of a retired model is
        // distinguishable from a read of an unknown one, and neither shape was
        // pinned.
        let models = doc["poe"]["models"]
            .as_object_mut()
            .expect("poe publishes models");
        assert!(
            models.remove("google/veo-3").is_some(),
            "the model being withdrawn must exist first, or the retirement is a \
             no-op and the case below reads an unknown model instead"
        );
        assert!(
            !models.is_empty(),
            "the provider must keep a model, or this withdraws the PROVIDER too \
             and the read refuses for a different reason than the one pinned"
        );
        serde_json::to_string(&doc).expect("the edited document serialises")
    };
    let obs = store
        .record_observation(&NewObservation {
            source: SourceId::ModelsDev,
            observed_at: Timestamp(1_500),
            outcome: ObservationOutcome::Changed { snapshot_seq: 2 },
            normalized_hash: Some("withdrawal-hash".into()),
            raw_hash: Some("withdrawal-raw".into()),
            etag: None,
            duration_ms: Some(210),
            detail: None,
        })
        .unwrap();
    let catalog = normalize_models_dev(withdrawn.as_bytes())
        .expect("the withdrawn document normalises")
        .catalog;
    let plan = plan_ingest(
        &store,
        &catalog,
        Timestamp(1_500),
        BoundaryKind::Observed,
        Some(obs),
    )
    .unwrap();
    assert!(
        plan.eras
            .iter()
            .any(|e| e.value_json.contains("missing_rate")),
        "the withdrawal must produce a tombstone, or the fixture pins nothing \
         new: got {} eras",
        plan.eras.len()
    );
    store.append_eras(&plan.eras).unwrap();

    // THE CURATED PLAN PRICES, applied exactly as boot applies them.
    //
    // Without this the whole `plan.prices` tool is absent from the fixture: I
    // shipped it and never pinned its wire shape, so a change to `prices`,
    // `unit_policy` or `tier_vocabulary` would redden nothing here. That is the
    // same gap the rate states had — a surface consumers pin from, covering
    // less than the wire carries.
    //
    // Applied through `store_rows(rows())` rather than hand-built, so the
    // fixture pins what the SHIPPED FILE produces. A synthetic row would pin a
    // shape nobody serves, and the curated file is the artifact under review.
    let plan_rows = fusiform_module::plan_prices::store_rows(fusiform_module::plan_prices::rows());
    assert!(
        !plan_rows.is_empty(),
        "the curated file must yield rows, or the plan.prices cases below pin an \
         empty answer and prove nothing"
    );
    store.append_plan_prices(&plan_rows).unwrap();

    // A failed poll, so the status payload carries a failure class. An
    // all-successful history would leave the fields a consumer reads during an
    // incident unpinned.
    store
        .record_observation(&NewObservation {
            source: SourceId::ModelsDev,
            observed_at: Timestamp(2_000),
            outcome: ObservationOutcome::Failed {
                class: fusiform_core::FailureClass::HttpStatus,
            },
            normalized_hash: None,
            raw_hash: None,
            etag: None,
            duration_ms: Some(87),
            detail: Some("upstream returned 503".into()),
        })
        .unwrap();

    // A correction, so the withheld list and the correction extent are pinned.
    // These are the fields a consumer needs exactly when something is wrong,
    // which is when nobody is regenerating fixtures.
    store
        .append_eras(&[NewEra {
            source: SourceId::ModelsDev,
            provider_id: "anthropic".into(),
            model_id: "claude-sonnet-4-5".into(),
            fact_key: FactKey::rate(TokenClass::Input),
            value_json: r#"{"state":"priced","currency":"USD","exponent":9,"units":3000000000}"#
                .into(),
            boundary_at: Timestamp(9_000),
            boundary_kind: BoundaryKind::Corrected(Correction {
                fields: vec![FieldId::Rate {
                    class: TokenClass::Input,
                }],
                affected_from: Timestamp(3_000),
                affected_until: Timestamp(9_000),
                reason: "normalizer scaled tiered rates by 1000x".to_string(),
            }),
            observation_id: None,
        }])
        .unwrap();

    (store, dir)
}

