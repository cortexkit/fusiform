/// Every field of every READ response appears somewhere in the fixture.
///
/// # Why this exists as a fence rather than as a habit
///
/// I have now found this gap twice by hand. First the rate STATES — the fixture
/// carried `priced` and nothing else, so a consumer pinning from it would never
/// meet `stated_zero` or `unpriced` and the first row carrying one would land on
/// a default arm. Then three whole fields: `plan.prices` (a tool I had shipped
/// that morning), `retired`, and `uncertain`.
///
/// Both were found by asking the same question by hand, and a third pass would
/// find a fourth gap later. This asks it on every run.
///
/// # What a miss costs
///
/// Consumers pin from these bytes -- ALF by my own recommendation.
///
/// MEASURED RATHER THAN ASSERTED, because the first version of this comment
/// said an absent field "can change and redden nothing", and that is false. The
/// three fields this fence was built after -- `retired`, `uncertain`,
/// `tier_vocabulary` -- are all asserted in `route.rs` by direct field access,
/// so a shape change would have reddened there.
///
/// What the fixture adds over those tests is a different guarantee, and it is
/// the one worth stating: a route test asserts the field a consumer ASKED FOR,
/// on a payload that test constructed. The fixture pins EVERY SERVED BYTE of a
/// real response, so it catches a change nobody thought to assert -- a renamed
/// neighbour, a dropped null, an added key. That is the class a targeted test
/// structurally cannot see, since it examines only what its author already had
/// in mind.
///
/// So the cost of a gap is narrower than I first wrote and still real: the
/// field keeps whatever coverage someone gave it deliberately, and loses the
/// coverage nobody had to think of.
///
/// # The three WRITE tools are exempt, and that is a finding rather than a gap
///
/// `catalog.correct`, `catalog.mark_artifact` and `catalog.retract_artifact`
/// have exactly one consumer: `ck-models`, in this repository. Their fields are
/// pinned where that consumer RENDERS them, in the CLI's own tests — checked
/// rather than assumed, and `restating_eras`, `had_live_mark` and `total_eras`
/// all appear there.
///
/// Adding them here would duplicate that coverage and make this fixture claim a
/// purpose it does not have: it pins what crosses the seam to OTHER repositories.
/// An operator tool whose only caller ships beside it does not cross one.
#[test]
fn every_read_response_field_reaches_the_fixture() {
    let src = include_str!("../../../fusiform-protocol/src/lib.rs");
    let golden: serde_json::Value = serde_json::from_str(GOLDEN).expect("the fixture parses");

    let mut present: std::collections::BTreeSet<String> = std::collections::BTreeSet::new();
    collect_keys(&golden, &mut present);
    assert!(
        present.len() > 40,
        "the fixture must carry a substantial key set, or the absence checks \
         below pass because nothing was collected: got {}",
        present.len()
    );

    // Source-scanned rather than reflected, because Rust has no runtime field
    // list and a hand-written one is a second statement of the struct that can
    // drift from it. The same reasoning as the currency-policy fence next door.
    let (checked, missing) = missing_response_fields(
        src,
        &present,
        &[
            "CatalogGetResponse",
            "PlaneWire",
            "BillingRuleWire",
            "HistoryResponse",
            "StatusResponse",
            "PlanPricesResponse",
            "PlanPriceWire",
        ],
    );

    assert!(
        checked >= 40,
        "this examined {checked} fields across seven structs; fewer than 40 means \
         the scan broke rather than the protocol shrinking"
    );

    assert!(
        missing.is_empty(),
        "These served fields appear in no golden payload: {missing:?}. Add a case that produces the field."
    );
}

fn missing_response_fields(
    src: &str,
    present: &std::collections::BTreeSet<String>,
    structs: &[&str],
) -> (usize, Vec<String>) {
    let mut checked = 0usize;
    let mut missing = Vec::new();
    for want in structs {
        let start = src
            .find(&format!("pub struct {want} {{"))
            .unwrap_or_else(|| panic!("{want} must exist in the protocol crate"));
        let body = &src[start..];
        let end = body.find("\n}").expect("a struct body closes");
        for line in body[..end].lines() {
            let line = line.trim();
            let Some(rest) = line.strip_prefix("pub ") else {
                continue;
            };
            let Some(field) = rest.split(':').next() else {
                continue;
            };
            // `pub struct` itself and any method; fields end with a type.
            if field.contains(' ') || field.is_empty() {
                continue;
            }
            checked += 1;
            if !present.contains(field) {
                missing.push(format!("{want}.{field}"));
            }
        }
    }

    (checked, missing)
}

#[test]
fn planted_missing_response_field_is_reported() {
    let mut present = std::collections::BTreeSet::new();
    collect_keys(&serde_json::json!({"known": null}), &mut present);
    assert_eq!(
        missing_response_fields(
            "pub struct Response {\n pub known: String,\n pub lost: String,\n}",
            &present,
            &["Response"]
        )
        .1,
        ["Response.lost"]
    );
}

/// Every object key anywhere in a document.
fn collect_keys(value: &serde_json::Value, out: &mut std::collections::BTreeSet<String>) {
    match value {
        serde_json::Value::Object(map) => {
            for (k, v) in map {
                out.insert(k.clone());
                collect_keys(v, out);
            }
        }
        serde_json::Value::Array(items) => {
            for v in items {
                collect_keys(v, out);
            }
        }
        _ => {}
    }
}

/// Every fact key in `SERVED_FACTS` appears in the fixture.
///
/// # A different vocabulary from the response fields next door
///
/// The fence above checks the KEYS OF THE ENVELOPE — `models`, `withheld`,
/// `retired`. This checks the keys INSIDE it, which is a separate list with a
/// separate authority: `SERVED_FACTS` in the protocol crate, the table that
/// tells a consumer what fusiform can ever serve.
///
/// Asked separately because the first fence was green while this one was not:
/// `rate.reasoning` appeared in no case, and the envelope was complete.
///
/// # Why a rare key needs a case rather than incidental coverage
///
/// `rate.reasoning` is carried by 166 of 6,213 reasoning-capable models in the
/// live catalog, measured 2026-09-19. A consumer is unlikely to meet one by
/// accident and certain to meet one eventually, which is the worst combination:
/// the decoder path is cold until it is load-bearing.
///
/// It is also the key where getting the shape wrong costs most. 115 of those
/// rows restate the model's output rate and 29 publish a different number —
/// alibaba bills reasoning at 2.5x to 3.3x output, perplexity's sonar at 0.38x
/// — so a consumer that defaults the key to the output rate is wrong in BOTH
/// directions, and the errors partially cancel in aggregate while every row is
/// wrong.
#[test]
fn every_served_fact_key_reaches_the_fixture() {
    let src = include_str!("../../../fusiform-protocol/src/lib.rs");
    let golden: serde_json::Value = serde_json::from_str(GOLDEN).expect("the fixture parses");

    let mut present: std::collections::BTreeSet<String> = std::collections::BTreeSet::new();
    collect_keys(&golden, &mut present);

    // Scanned from the table rather than listed here, so a key added to
    // `SERVED_FACTS` is checked without anyone remembering this test.
    //
    // SCOPED TO THE TABLE'S BODY, not to the whole file. My first version
    // matched every `key: "` in lib.rs and happened to collect exactly the 15
    // SERVED_FACTS entries — correct by accident rather than by construction,
    // since any other struct with a `key` field would have been swept in and
    // this fence would then demand a fixture example of something that is not a
    // served fact.
    //
    // The failure direction was safe (a loud, diagnosable red naming the key)
    // which is exactly why it would have survived: nothing would have gone
    // wrong until someone added an unrelated field, and the scan's SUBJECT
    // would have been wrong the whole time.
    let (count, missing) = missing_served_fact_keys(src, &present);
    assert!(
        count >= 15,
        "SERVED_FACTS carried 15 entries when this was written; found {count}, which \
         means the scan broke rather than the table shrinking"
    );
    assert!(
        missing.is_empty(),
        "served fact keys absent from the fixture: {missing:?}"
    );
}

fn missing_served_fact_keys(
    src: &str,
    present: &std::collections::BTreeSet<String>,
) -> (usize, Vec<String>) {
    let table = {
        let start = src
            .find("pub const SERVED_FACTS")
            .expect("the served-facts table must exist");
        let body = &src[start..];
        let end = body.find("\n];").expect("the table closes");
        &body[..end]
    };
    let keys: Vec<&str> = table
        .match_indices("key: \"")
        .filter_map(|(i, _)| {
            let rest = &table[i + 6..];
            rest.find('"').map(|end| &rest[..end])
        })
        .collect();

    let missing = keys
        .iter()
        .filter(|k| !present.contains(**k))
        .map(|k| (*k).to_string())
        .collect();
    (keys.len(), missing)
}

#[test]
fn planted_missing_served_fact_key_is_reported() {
    let mut present = std::collections::BTreeSet::new();
    collect_keys(&serde_json::json!({"known": 1}), &mut present);
    assert_eq!(missing_served_fact_keys("pub const SERVED_FACTS: &[Fact] = &[\n Fact { key: \"known\" },\n Fact { key: \"lost\" },\n];", &present).1, ["lost"]);
}
