/// The one field that cannot be pinned, and what stands in for it.
const NOW_PLACEHOLDER: i64 = -1;

fn render() -> String {
    let (store, _dir) = store();
    let mut doc = serde_json::Map::new();
    for (label, body) in cases() {
        let response = serve_tool_call(&store, body.as_bytes())
            .unwrap_or_else(|e| panic!("{label} must serve: {e:?}"));
        let mut value = serde_json::to_value(&response).unwrap();

        // A read with no `at_ms` resolves to wall-clock now. Substituted rather
        // than dropped: the KEY stays in the fixture, so a rename or a type
        // change still shows up as a diff, and only the unpinnable number is
        // replaced. Asserted separately below that the real value is sane.
        if !body.contains("at_ms") {
            if let Some(resolved) = value.get_mut("resolved_at_ms") {
                *resolved = serde_json::json!(NOW_PLACEHOLDER);
            }
        }

        doc.insert(
            label.to_string(),
            serde_json::json!({
                "request": serde_json::from_str::<serde_json::Value>(&body).unwrap(),
                "response": value,
            }),
        );
    }
    let mut text = serde_json::to_string_pretty(&serde_json::Value::Object(doc)).unwrap();
    text.push('\n');
    text
}

/// The substituted field really does carry a current instant.
///
/// The placeholder above keeps the fixture stable, and on its own it would let
/// `resolved_at_ms` become anything at all — zero, a constant, last week —
/// without any test noticing. This checks the real value.
#[test]
fn a_current_read_resolves_to_an_instant_near_now() {
    let (store, _dir) = store();
    let before = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap()
        .as_millis() as i64;

    let response = serve_tool_call(
        &store,
        br#"{"name":"catalog.get","arguments":{"provider_id":"anthropic","model_id":"claude-sonnet-4-5"}}"#,
    )
    .unwrap();
    let value = serde_json::to_value(&response).unwrap();
    let resolved = value
        .get("resolved_at_ms")
        .and_then(|v| v.as_i64())
        .expect("a current read reports the instant it resolved to");

    let after = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap()
        .as_millis() as i64;

    assert!(
        resolved >= before && resolved <= after,
        "a current read must resolve to now: got {resolved}, expected between \
         {before} and {after}"
    );
}

/// The served payloads have not changed.
#[test]
fn the_served_payloads_match_the_golden_fixture() {
    let rendered = render_all();

    if std::env::var("UPDATE_GOLDEN").is_ok() {
        let path = concat!(env!("CARGO_MANIFEST_DIR"), "/fixtures/served-payloads.json");
        std::fs::write(path, &rendered).unwrap();
        eprintln!("golden fixture regenerated at {path} — review the diff");
        return;
    }

    if rendered != GOLDEN {
        // The diff rather than the whole document: a 200-line dump of two
        // similar payloads is unreadable, and the changed lines are the point.
        let mut differing = Vec::new();
        for (i, (a, b)) in GOLDEN.lines().zip(rendered.lines()).enumerate() {
            if a != b {
                differing.push(format!("  line {}:\n    was: {a}\n    now: {b}", i + 1));
            }
        }
        if GOLDEN.lines().count() != rendered.lines().count() {
            differing.push(format!(
                "  line count: was {}, now {}",
                GOLDEN.lines().count(),
                rendered.lines().count()
            ));
        }
        panic!(
            "the served payload changed. A consumer parses these bytes.\n\n{}\n\n\
             If the change is intended, regenerate with:\n  \
             UPDATE_GOLDEN=1 cargo test -p fusiform-module --test it golden_payload::\n\
             and bump fusiform-protocol's version — CI enforces that separately.",
            differing.join("\n")
        );
    }
}

